# Concept of the Day: Support Vector Machines (SVM)
#
# Explanation: Imagine you have Red dots and Blue dots on a paper.
# You want to draw a line to separate them.
# You could draw many lines.
# SVM finds the Best Line (Hyperplane).
#
# The Margin: The "street" between the line and the nearest dots.
# SVM tries to make this street as wide as possible.
#
# Kernel Trick: If the dots are mixed up (a circle of red inside a ring of blue), SVM projects them into 3D space so it can slice them with a flat sheet.