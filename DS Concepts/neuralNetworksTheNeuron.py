# Concept of the Day: Neural Networks (The Neuron)
#
# Explanation: A Neural Network is just math loosely inspired by the brain. A single Neuron (Perceptron) does three things:
#
# Input ($x$): Takes in numbers.
#
# Weights ($w$): Multiplies them by importance (Weights).
#
# Activation: Passes the sum through a filter (like "If sum > 0, fire").
#
# Output = Activation (sum (Input * Weight) + Bias)