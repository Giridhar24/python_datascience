# Concept of the Day: Time Series Analysis
#
# Explanation: Data that changes over time (Stock prices, Temperature) is special.
#
# You can't just shuffle it randomly (because Tuesday follows Monday).
#
# Trend: The long-term direction (Up/Down).
#
# Seasonality: Repeating patterns (Ice cream sales go up every Summer).
#
# Noise: Random spikes. ARIMA is a popular model for forecasting this type of data.