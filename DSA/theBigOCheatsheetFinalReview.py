# Concept of the Day: The Big O Cheatsheet (Final Review)
#
# Explanation: As you graduate, keep this mental map for every line of code you write.
#
# O(1) (Excellent): Hash Maps, Array Access. (Instant).
#
# O(log N) (Good): Binary Search, BST, Heaps. (Cuts problem in half).
#
# O(N) (Fair): Loops, Unsorted Search. (Reads everything once).
#
# O(N log N) (Okay): Merge Sort, Quick Sort, Sorting.
#
# O(N^2) (Bad): Nested Loops (Bubble Sort). Avoid for large data.
#
# O(2 ^ N) (Terrible): Recursion without Memoization.

